function carregarNoticias(tipo) {
  const data = noticias[tipo];

  document.getElementById("titulo").innerText = "notícias postadas";

  if (tipo === "arte") {
    document.getElementById("subtitulo").innerText = "arte e cultura.";
    document.body.classList.add("arte");
    document.body.classList.remove("top", "natureza");
  } else if (tipo === "top") {
    document.getElementById("subtitulo").innerText = "avanços tecnológicos.";
    document.body.classList.add("top");
    document.body.classList.remove("arte", "natureza");
  } else if (tipo === "natureza") {
    document.getElementById("subtitulo").innerText = "natureza.";
    document.body.classList.add("natureza");
    document.body.classList.remove("arte", "top");
  }

  document.querySelector(".not1").innerHTML = `
    <img src="${data.not1.img}" alt="Imagem notícia">
    <div class="titulo-icons">
      <h3 class="titulo-card-big">${data.not1.titulo}</h3>
      <div class="icons icons-line">
        <i class='bx bx-share-alt'></i>
        <i class='bx bx-bookmark'></i>
      </div>
    </div>
    <p class="resumo-card">${data.not1.resumo}</p>
  `;

  for (let i = 2; i <= 5; i++) {
    const not = data[`not${i}`];
    document.querySelector(`.not${i}`).innerHTML = `
      <h3 class="titulo-card">${not.titulo}</h3>
      <p class="resumo-card">${not.resumo}</p>
      <div class="icons-line">
        <i class='bx bx-share-alt'></i>
        <i class='bx bx-bookmark'></i>
      </div>
      <img src="${not.img}" alt="Imagem notícia ${i}">
      <p class="mini-desc">${not.mini}</p>
    `;
  }

  document.querySelector(".qad").innerHTML = `
    <div class="qad-container">
      <div class="qad-esquerda">
        <h3 class="titulo-card">${data.qad.titulo}</h3>
        <p class="resumo-card">${data.qad.resumo}</p>
      </div>
      <div class="qad-direita">
        <div class="icons icons-right icons-line">
          <i class='bx bx-share-alt'></i>
          <i class='bx bx-bookmark'></i>
        </div>
        <img src="${data.qad.img}" alt="Imagem notícia destaque" class="imagem-card">
        <p class="mini-desc">${data.qad.mini}</p>
      </div>
    </div>
  `;

  document.querySelectorAll(".mini-desc").forEach((desc) => {
    desc.style.fontSize = "0.85rem";
    desc.style.color = "#555";
    desc.style.textAlign = "justify";
    desc.style.lineHeight = "1.4";
  });
}

// Load "Arts and Culture" news by default when the page loads
document.addEventListener("DOMContentLoaded", () => {
  carregarNoticias("arte");
});